/**
 * Таксономия тем. Портирована из `utils/content_library.py::_TAG_SYNONYMS`
 * Telegram-бота — теги общие, чтобы аналитика двух продуктов сходилась.
 *
 * Синоним — начало слова, а не подстрока: «море» сидит внутри
 * «терМОРЕгуляции», и без границы слова любое упоминание терморегуляции
 * притягивало бы тему пляжа.
 */

