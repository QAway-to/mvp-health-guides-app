/**
 * Карточка бизнес-контакта.
 *
 * Устройство карточки — две колонки, и это не приём вёрстки, а сама модель.
 * Слева то, что человек ищет, справа то, что у него есть. Матч возникает
 * между колонками разных людей: мой запрос против чужого предложения.
 *
 * Поэтому обе колонки — записи одного типа `Entry`. Одна и та же «аренда
 * помещения» у одного стоит в требованиях, у другого в предложениях, и
 * описывается она одинаково: иначе их не сопоставить.
 */

/**
 * Что вообще ходит между людьми.
 *
 * Список закрытый и короткий намеренно. Свободный текст сопоставить нельзя —
 * а вид ресурса это первое, по чему отсекается заведомо чужое: инвестору с
 * деньгами не предлагают экспертность, пока он её не запросил.
 */
export type AssetKind = 'space' | 'contacts' | 'capital' | 'team' | 'expertise';

/** Одна строка в колонке: что именно ищут или что именно дают. */
export type Entry = {
  readonly id: string;
  readonly kind: AssetKind;
  /** Суть в одну строку — то, что видно в колонке. */
  readonly title: string;
  /** Условия и подробности: метраж, сумма, сроки, отрасль. */
  readonly detail: string;
  /**
   * Ключи для сопоставления.
   *
   * Отдельно от заголовка, потому что заголовок пишет человек, а сходятся
   * карточки по общему словарю. «Помещение под кофейню» и «первый этаж,
   * street retail» — это один тег `horeca`, хотя слова разные.
   */
  readonly tags: readonly string[];
};

export type Card = {
  readonly id: string;
  readonly name: string;
  readonly role: string;
  readonly company?: string;
  readonly city: string;
  /** Одна фраза о себе — то, что читают до колонок. */
  readonly about: string;
  /** Левая колонка: что ищу. */
  readonly needs: readonly Entry[];
  /** Правая колонка: что имею и предлагаю. */
  readonly offers: readonly Entry[];
};
